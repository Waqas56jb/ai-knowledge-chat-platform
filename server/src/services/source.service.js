/**
 * Knowledge sources: user-facing (access-filtered) and admin views.
 * User access is ALWAYS decided by the database function ai_knowledge_chat_accessible_source_ids —
 * the same function used by RAG retrieval — so the API can never show more than retrieval uses (or vice versa).
 */
import { one, many, tx, query } from '../config/database.js';
import { T, FN } from '../config/constants.js';
import { ApiError } from '../utils/ApiError.js';
import { recordAudit, entityActivity } from './audit.service.js';
import { removeDocument, signedUrl } from './document.service.js';
import { videoUrl } from './youtube.service.js';

export const TYPE_GROUP = { youtube: 'youtube', pdf: 'document', docx: 'document', txt: 'text', markdown: 'text', business_knowledge: 'text', client_conversation: 'conversation' };

export const sourceOut = s => s && ({
  id: s.id, title: s.title, description: s.description, type: s.source_type, group: TYPE_GROUP[s.source_type],
  url: s.source_url, channelName: s.channel_name, durationSeconds: s.duration_seconds, visibility: s.visibility,
  status: s.status, tags: s.tags || [], chunkCount: s.chunk_count, errorMessage: s.error_message,
  file: s.metadata?.file || null, youtube: s.metadata?.videoId ? { videoId: s.metadata.videoId, thumbnail: `https://i.ytimg.com/vi/${s.metadata.videoId}/hqdefault.jpg`, transcriptLanguage: s.metadata.transcript?.language || null, transcriptProvider: s.metadata.transcript?.provider || null, autoGenerated: !!s.metadata.transcript?.autoGenerated } : null,
  isChannel: s.metadata?.kind === 'channel',
  hideCitations: !!s.metadata?.hideCitations,
  ownerId: s.owner_id, ownerName: s.owner_name || null, createdAt: s.created_at, updatedAt: s.updated_at, indexedAt: s.indexed_at,
  ...(s.notes !== undefined && s.include_admin ? { notes: s.notes, metadata: s.metadata } : {})
});

const BASE = `select s.*, p.full_name as owner_name from ${T.sources} s left join ${T.profiles} p on p.id = s.owner_id`;
const ADDED = { '7d': 7, '30d': 30, '90d': 90 };
const SORTS = { title: 's.title', createdAt: 's.created_at', updatedAt: 's.updated_at', chunkCount: 's.chunk_count', status: 's.status', type: 's.source_type' };

function filters(f, params, where) {
  if (f.q) { params.push(`%${f.q}%`); where.push(`(s.title ilike $${params.length} or s.description ilike $${params.length} or array_to_string(s.tags, ' ') ilike $${params.length})`); }
  if (f.type) {
    const types = f.type in GROUP_TYPES ? GROUP_TYPES[f.type] : [f.type];
    params.push(types); where.push(`s.source_type = any($${params.length}::text[])`);
  }
  if (f.status) { params.push(f.status); where.push(`s.status = $${params.length}`); }
  if (f.ownerId) { params.push(f.ownerId); where.push(`s.owner_id = $${params.length}`); }
  if (f.added && ADDED[f.added]) where.push(`s.created_at >= now() - interval '${ADDED[f.added]} days'`);
}
const GROUP_TYPES = { document: ['pdf', 'docx'], text: ['txt', 'markdown', 'business_knowledge'], conversation: ['client_conversation'] };

/** Sources the user may see (user-facing browser). Disabled/failed/pending ones are hidden from non-admins. */
export async function listAccessibleSources(user, f, { limit, offset }) {
  const params = [user.id]; const where = [`s.id in (select ${FN.accessibleSources}($1))`];
  if (user.role !== 'admin') where.push(`s.status = 'indexed'`);
  where.push(`coalesce(s.metadata ->> 'kind', '') <> 'channel'`);
  filters(f, params, where);
  const w = `where ${where.join(' and ')}`;
  const total = (await one(`select count(*)::int as n from ${T.sources} s ${w}`, params)).n;
  const order = `${SORTS[f.sort] || 's.created_at'} ${f.dir === 'asc' ? 'asc' : 'desc'}, s.id`;
  const rows = await many(`${BASE} ${w} order by ${order} limit ${Number(limit)} offset ${Number(offset)}`, params);
  const counts = await many(`select s.source_type as type, count(*)::int as n from ${T.sources} s where s.id in (select ${FN.accessibleSources}($1)) ${user.role !== 'admin' ? "and s.status = 'indexed'" : ''} and coalesce(s.metadata ->> 'kind', '') <> 'channel' group by 1`, [user.id]);
  return { rows: rows.map(sourceOut), total, counts };
}

export async function assertSourceAccess(user, sourceId) {
  const r = await one(`select 1 from ${T.sources} s where s.id = $2 and s.id in (select ${FN.accessibleSources}($1)) ${user.role !== 'admin' ? "and s.status = 'indexed'" : ''}`, [user.id, sourceId]);
  if (!r) throw ApiError.notFound('Source not found.'); // 404, not 403: do not reveal that it exists
}

export async function getAccessibleSource(user, id) {
  await assertSourceAccess(user, id);
  const s = await one(`${BASE} where s.id = $1`, [id]);
  const linked = await many(`select distinct c.id, c.title, c.updated_at from ${T.conversations} c join ${T.messages} m on m.conversation_id = c.id
     where c.user_id = $1 and m.citations @> $2::jsonb order by c.updated_at desc limit 20`, [user.id, JSON.stringify([{ sourceId: id }])]);
  return { ...sourceOut(s), linkedConversations: linked.map(c => ({ id: c.id, title: c.title, updatedAt: c.updated_at })) };
}

export async function listChunks(user, sourceId, { limit, offset }) {
  await assertSourceAccess(user, sourceId);
  const s = await one(`select source_type, metadata from ${T.sources} where id = $1`, [sourceId]);
  const total = (await one(`select count(*)::int as n from ${T.chunks} where source_id = $1`, [sourceId])).n;
  const rows = await many(`select id, chunk_index, content, token_count, start_seconds, end_seconds, page_number from ${T.chunks} where source_id = $1 order by chunk_index limit $2 offset $3`, [sourceId, limit, offset]);
  return {
    rows: rows.map(c => ({ id: c.id, index: c.chunk_index, content: c.content, tokenCount: c.token_count, startSeconds: c.start_seconds, endSeconds: c.end_seconds, pageNumber: c.page_number, url: s?.metadata?.videoId && c.start_seconds != null ? videoUrl(s.metadata.videoId, c.start_seconds) : null })),
    total
  };
}

/* ------------------------------- admin ------------------------------- */

export async function adminListSources(f, { limit, offset }) {
  const params = []; const where = [];
  filters(f, params, where);
  const w = where.length ? `where ${where.join(' and ')}` : '';
  const total = (await one(`select count(*)::int as n from ${T.sources} s ${w}`, params)).n;
  const order = `${SORTS[f.sort] || 's.created_at'} ${f.dir === 'asc' ? 'asc' : 'desc'}, s.id`;
  const rows = await many(`${BASE} ${w} order by ${order} limit ${Number(limit)} offset ${Number(offset)}`, params);
  const active = await many(`select source_id, id, status, progress, current_step from ${T.jobs} where status in ('queued','processing') and source_id = any($1::uuid[])`, [rows.map(r => r.id)]);
  return { rows: rows.map(r => ({ ...sourceOut(r), activeJob: (a => a && { id: a.id, status: a.status, progress: a.progress, step: a.current_step })(active.find(a => a.source_id === r.id)) })), total };
}

export async function knowledgeStats() {
  return one(`select count(*)::int as total,
      count(*) filter (where status = 'indexed')::int as indexed, count(*) filter (where status = 'pending')::int as pending,
      count(*) filter (where status = 'processing')::int as processing, count(*) filter (where status = 'failed')::int as failed,
      count(*) filter (where status = 'disabled')::int as disabled,
      count(*) filter (where created_at > now() - interval '7 days')::int as recent,
      coalesce(sum(chunk_count) filter (where status = 'indexed'), 0)::int as chunks
    from ${T.sources}`);
}

export async function adminGetSource(id) {
  const s = await one(`${BASE} where s.id = $1`, [id]);
  if (!s) throw ApiError.notFound('Source not found.');
  const [allowed, jobs, related, contents, children, activity] = await Promise.all([
    many(`select a.user_id as id, p.full_name as name, p.email from ${T.sourceAccess} a join ${T.profiles} p on p.id = a.user_id where a.source_id = $1 order by p.full_name`, [id]),
    many(`select id, job_type, status, progress, current_step, attempts, error_message, parent_job_id, created_at, started_at, completed_at from ${T.jobs} where source_id = $1 order by created_at desc limit 50`, [id]),
    many(`select c.id, c.title, c.user_id, p.full_name as user_name, c.updated_at,
            (select count(*)::int from ${T.messages} m, jsonb_array_elements(m.citations) ci where m.conversation_id = c.id and ci ->> 'sourceId' = $1::text) as citations
          from ${T.conversations} c left join ${T.profiles} p on p.id = c.user_id
          where exists (select 1 from ${T.messages} m where m.conversation_id = c.id and m.citations @> $2::jsonb) order by c.updated_at desc limit 50`, [id, JSON.stringify([{ sourceId: id }])]),
    one(`select left(content, 6000) as preview, char_length(content) as length, language, provider from ${T.sourceContents} where source_id = $1`, [id]),
    s.metadata?.kind === 'channel' ? many(`select id, title, status, chunk_count from ${T.sources} where metadata ->> 'channelSourceId' = $1 order by created_at`, [id]) : [],
    entityActivity('source', id)
  ]);
  return {
    ...sourceOut({ ...s, include_admin: true }),
    allowedUsers: allowed,
    jobs: jobs.map(jobOut),
    relatedConversations: related.map(r => ({ id: r.id, title: r.title, userId: r.user_id, userName: r.user_name, updatedAt: r.updated_at, citations: r.citations })),
    content: contents ? { preview: contents.preview, length: contents.length, language: contents.language, provider: contents.provider } : null,
    channelVideos: children.map(c => ({ id: c.id, title: c.title, status: c.status, chunkCount: c.chunk_count })),
    activity
  };
}

export const jobOut = j => j && ({
  id: j.id, sourceId: j.source_id, sourceTitle: j.source_title, type: j.job_type, status: j.status, progress: j.progress, step: j.current_step,
  attempts: j.attempts, maxAttempts: j.max_attempts, error: j.error_message, parentJobId: j.parent_job_id,
  createdAt: j.created_at, startedAt: j.started_at, completedAt: j.completed_at, updatedAt: j.updated_at,
  ...(j.logs ? { logs: j.logs } : {}), ...(j.result ? { result: j.result } : {})
});

/** changes: { title, description, tags, visibility, allowedUserIds, notes } */
export async function updateSource(id, changes, actor, req) {
  const before = await one(`select * from ${T.sources} where id = $1`, [id]);
  if (!before) throw ApiError.notFound('Source not found.');
  await tx(async db => {
    const map = { title: 'title', description: 'description', tags: 'tags', visibility: 'visibility', notes: 'notes' };
    const sets = []; const params = [id];
    for (const [k, col] of Object.entries(map)) if (changes[k] !== undefined) { params.push(changes[k]); sets.push(`${col} = $${params.length}`); }
    if (sets.length) await db.query(`update ${T.sources} set ${sets.join(', ')} where id = $1`, params);
    if (typeof changes.hideCitations === 'boolean') {
      await db.query(`update ${T.sources} set metadata = metadata || jsonb_build_object('hideCitations', $2::boolean) where id = $1`, [id, changes.hideCitations]);
    }
    if (Array.isArray(changes.allowedUserIds)) {
      await db.query(`delete from ${T.sourceAccess} where source_id = $1`, [id]);
      if (changes.allowedUserIds.length) await db.query(`insert into ${T.sourceAccess} (source_id, user_id) select $1, p.id from ${T.profiles} p where p.id = any($2::uuid[]) on conflict do nothing`, [id, changes.allowedUserIds]);
    }
    await recordAudit({ actor, action: 'source.updated', entityType: 'source', entityId: id, entityLabel: changes.title || before.title, details: { changed: Object.keys(changes) }, req }, db);
  });
  return adminGetSource(id);
}

/** Hide or show citations for many sources at once (the content is still used to answer). */
export async function bulkSetCitations(ids, hide, actor, req) {
  const r = await query(`update ${T.sources} set metadata = metadata || jsonb_build_object('hideCitations', $2::boolean)
                          where id = any($1::uuid[]) and coalesce((metadata ->> 'hideCitations')::boolean, false) <> $2`, [ids, hide]);
  await recordAudit({ actor, action: hide ? 'source.citations_hidden' : 'source.citations_shown', entityType: 'source', entityLabel: `${r.rowCount} sources`, details: { ids, updated: r.rowCount }, req });
  return { updated: r.rowCount };
}

export async function setSourceEnabled(id, enabled, actor, req) {
  const s = await one(`select id, title, status, chunk_count from ${T.sources} where id = $1`, [id]);
  if (!s) throw ApiError.notFound('Source not found.');
  if (enabled && s.status !== 'disabled') throw ApiError.conflict('The source is not disabled.');
  if (!enabled && s.status === 'disabled') throw ApiError.conflict('The source is already disabled.');
  if (!enabled && s.status === 'processing') throw ApiError.conflict('Wait for processing to finish before disabling this source.');
  const next = enabled ? (s.chunk_count > 0 ? 'indexed' : 'pending') : 'disabled';
  await one(`update ${T.sources} set status = $2 where id = $1 returning id`, [id, next]);
  if (!enabled) await one(`update ${T.jobs} set status = 'cancelled', completed_at = now() where source_id = $1 and status = 'queued' returning id`, [id]);
  await recordAudit({ actor, action: enabled ? 'source.enabled' : 'source.disabled', entityType: 'source', entityId: id, entityLabel: s.title, req });
  return adminGetSource(id);
}

export async function deleteSource(id, actor, req) {
  const s = await one(`select id, title, storage_path, status from ${T.sources} where id = $1`, [id]);
  if (!s) throw ApiError.notFound('Source not found.');
  if (s.status === 'processing') throw ApiError.conflict('Wait for processing to finish before deleting this source.');
  await one(`delete from ${T.sources} where id = $1 returning id`, [id]); // chunks, contents, access, jobs cascade
  await removeDocument(s.storage_path);
  await recordAudit({ actor, action: 'source.deleted', entityType: 'source', entityId: id, entityLabel: s.title, req });
}

export async function sourceDownloadUrl(user, id) {
  if (user.role !== 'admin') await assertSourceAccess(user, id);
  const s = await one(`select storage_path from ${T.sources} where id = $1`, [id]);
  if (!s?.storage_path) throw ApiError.notFound('This source has no downloadable file.');
  return signedUrl(s.storage_path);
}

