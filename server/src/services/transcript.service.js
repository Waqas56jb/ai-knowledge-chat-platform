/**
 * Transcript providers (replaceable). getTranscript(videoId) → { segments: [{ text, start, duration }] (seconds),
 * language, provider, durationSeconds }.
 *
 * - `youtube-public-captions` (default): reads the public caption track that YouTube's own player
 *   loads for a public video. No login, no captcha solving, no private content. Prefers English
 *   human-made captions, then English auto-captions, then the first available track.
 *   Videos with captions disabled, age/region restrictions, or rate limiting cannot be transcribed.
 * - `manual`: an administrator pastes the transcript text (always works; see ingestion.service).
 */
import { ApiError } from '../utils/ApiError.js';

const CLIENT = { clientName: 'ANDROID', clientVersion: '20.10.38', androidSdkVersion: 34, hl: 'en' };
const UA = 'com.google.android.youtube/20.10.38 (Linux; U; Android 14)';
const decode = s => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");

async function fetchJson(url, init, ms = 15000) {
  const ctrl = new AbortController(); const t = setTimeout(() => ctrl.abort(), ms);
  try {
    const r = await fetch(url, { ...init, signal: ctrl.signal });
    if (r.status === 429) { const e = ApiError.unavailable('YouTube is rate-limiting transcript requests from this server. The job will retry later.'); e.transient = true; throw e; }
    if (!r.ok) { const e = ApiError.unavailable(`YouTube responded with HTTP ${r.status}.`); e.transient = r.status >= 500; throw e; }
    return await r.json();
  } catch (e) {
    if (e.name === 'AbortError') { const err = ApiError.unavailable('YouTube did not respond in time.'); err.transient = true; throw err; }
    throw e;
  } finally { clearTimeout(t); }
}

function pickTrack(tracks) {
  const en = tracks.filter(t => /^en(-|$)/.test(t.languageCode));
  return en.find(t => t.kind !== 'asr') || en[0] || tracks.find(t => t.kind !== 'asr') || tracks[0] || null;
}

export const youtubePublicCaptions = {
  name: 'youtube-public-captions',
  async getTranscript(videoId) {
    const player = await fetchJson('https://www.youtube.com/youtubei/v1/player?prettyPrint=false', {
      method: 'POST', headers: { 'Content-Type': 'application/json', 'User-Agent': UA }, body: JSON.stringify({ context: { client: CLIENT }, videoId })
    });
    const status = player?.playabilityStatus?.status;
    // "Sign in to confirm you're not a bot" is YouTube throttling this server, not a property of the video: retry later
    if (status === 'LOGIN_REQUIRED' && /bot/i.test(player?.playabilityStatus?.reason || '')) {
      const e = ApiError.unavailable('YouTube is temporarily blocking transcript requests from this server (bot check). The job will retry later.'); e.transient = true; throw e;
    }
    if (status && status !== 'OK') { const e = ApiError.validation(`This video is not publicly playable (${String(status).toLowerCase()}), so its transcript cannot be fetched.`); e.permanent = true; throw e; }
    const tracks = player?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
    const track = pickTrack(tracks);
    if (!track?.baseUrl || !/^https:\/\/www\.youtube\.com\/api\/timedtext/.test(track.baseUrl)) {
      const e = ApiError.validation('This video has no captions available, so it cannot be transcribed automatically. Paste the transcript manually instead.'); e.permanent = true; throw e;
    }
    const data = await fetchJson(track.baseUrl.replace(/&fmt=[^&]*/, '') + '&fmt=json3', { headers: { 'User-Agent': UA } });
    const segments = (data.events || []).filter(e => Array.isArray(e.segs))
      .map(e => ({ text: decode(e.segs.map(s => s.utf8 || '').join('')).replace(/\s+/g, ' ').trim(), start: (e.tStartMs || 0) / 1000, duration: (e.dDurationMs || 0) / 1000 }))
      .filter(s => s.text && s.text !== '[Music]');
    if (!segments.length) { const e = ApiError.validation('The caption track for this video is empty.'); e.permanent = true; throw e; }
    const durationSeconds = Number(player?.videoDetails?.lengthSeconds) || Math.ceil(segments[segments.length - 1].start + segments[segments.length - 1].duration);
    return { segments, language: track.languageCode, autoGenerated: track.kind === 'asr', provider: this.name, durationSeconds, title: player?.videoDetails?.title || null, channelName: player?.videoDetails?.author || null };
  }
};

/**
 * Parse a pasted transcript. Lines may start with timestamps ("01:23", "1:02:03", "[00:45]");
 * lines without timestamps are attached to the previous timestamp.
 */
export function parseManualTranscript(text) {
  const lines = String(text).split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  const segments = []; let lastStart = 0;
  for (const line of lines) {
    const m = line.match(/^\[?((?:\d{1,2}:)?\d{1,2}:\d{2})\]?\s*[-–:]?\s*(.*)$/);
    if (m) {
      const parts = m[1].split(':').map(Number);
      lastStart = parts.reduce((a, n) => a * 60 + n, 0);
      if (m[2]) segments.push({ text: m[2], start: lastStart, duration: 0 });
    } else segments.push({ text: line, start: lastStart, duration: 0 });
  }
  // derive durations from the next segment's start
  for (let i = 0; i < segments.length - 1; i++) segments[i].duration = Math.max(0, segments[i + 1].start - segments[i].start);
  return { segments, language: null, provider: 'manual', hasTimestamps: lines.some(l => /^\[?(?:\d{1,2}:)?\d{1,2}:\d{2}/.test(l)) };
}

export const transcriptProvider = youtubePublicCaptions;
