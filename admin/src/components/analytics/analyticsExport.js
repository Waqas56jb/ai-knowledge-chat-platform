import { DATE_RANGES } from '../../constants/domain';
import { downloadFile } from '../../utils/csv';
import { exportAnalytics } from '../../services/analyticsService';
import { formatDate, formatDateTime, formatInputDate, formatNumber, formatPercent } from '../../utils/format';

/** Human label for a range: "Last 30 days" or "Mar 1, 2026 – Mar 14, 2026". */
export function rangeLabel(range, analytics) {
  if (typeof range === 'string') return (DATE_RANGES.find(([v]) => v === range) || [range, range])[1];
  return analytics ? `${formatDate(analytics.from)} – ${formatDate(analytics.to)}` : `${range.from} – ${range.to}`;
}

/** Filename-safe slug for a range: "30d" or "2026-03-01-to-2026-03-14". */
export function rangeSlug(range, analytics) {
  if (typeof range === 'string') return range;
  return analytics ? `${formatInputDate(analytics.from)}-to-${formatInputDate(analytics.to)}` : `${range.from}-to-${range.to}`;
}

/** Download the selected range as CSV, generated by the server (`?format=csv`). */
export function exportAnalyticsCsv(range) {
  return exportAnalytics(range);
}

const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const pct = (v, total) => (total ? formatPercent((v / total) * 100) : '0%');
const table = (head, rows) => `<table><thead><tr>${head.map(h => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map(r => `<tr>${r.map(c => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
const delta = d => (d == null ? '—' : `${d > 0 ? '+' : ''}${d}%`);

/** Self-contained HTML summary of the current range. */
export function buildAnalyticsReport(a, range) {
  const k = a.kpis, label = rangeLabel(range, a), generated = formatDateTime(new Date());
  const questions = a.totals.questions;
  const kpiRows = [
    ['Total users', formatNumber(k.totalUsers.value), delta(k.totalUsers.delta)],
    ['Active users (peak day)', formatNumber(k.activeUsers.value), delta(k.activeUsers.delta)],
    ['New registrations', formatNumber(k.newRegistrations.value), delta(k.newRegistrations.delta)],
    ['Conversations', formatNumber(k.conversations.value), delta(k.conversations.delta)],
    ['Questions asked', formatNumber(k.questions.value), delta(k.questions.delta)],
    ['Answers with citations', formatNumber(k.answered.value), delta(k.answered.delta)],
    ['Citation rate', formatPercent(k.citationRate.value), '—'],
    ['Unsupported queries', formatNumber(k.unsupported.value), delta(k.unsupported.delta)],
    ['Knowledge sources', formatNumber(k.sources.value), '—'],
    ['Processing success rate', formatPercent(k.processingSuccess.value), '—']
  ];
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>DTS AI analytics report — ${esc(label)}</title>
<style>
  :root { color-scheme: light; }
  body { font: 14px/1.55 system-ui, -apple-system, "Segoe UI", sans-serif; color: #18160f; background: #faf8f4; margin: 0; padding: 32px 16px; }
  main { max-width: 860px; margin: 0 auto; background: #fff; border: 1px solid #e8e4db; border-radius: 16px; padding: 32px; }
  h1 { font-size: 24px; margin: 0 0 4px; } h2 { font-size: 16px; margin: 28px 0 10px; }
  .meta { color: #686259; margin: 0; }
  table { width: 100%; border-collapse: collapse; font-size: 13.5px; }
  th, td { text-align: left; padding: 8px 10px; border-bottom: 1px solid #ece8df; }
  th { color: #686259; font-weight: 600; font-size: 12px; text-transform: uppercase; letter-spacing: .04em; }
  td:not(:first-child), th:not(:first-child) { text-align: right; }
  footer { margin-top: 28px; color: #928c82; font-size: 12px; }
</style></head>
<body><main>
  <h1>Analytics report</h1>
  <p class="meta">DTS AI admin console · ${esc(label)} (${esc(formatDate(a.from))} – ${esc(formatDate(a.to))}, ${a.days} ${a.days === 1 ? 'day' : 'days'})</p>
  <p class="meta">Generated ${esc(generated)}</p>

  <h2>Key metrics</h2>
  ${table(['Metric', 'Value', 'Change vs previous period'], kpiRows)}

  <h2>Query outcomes</h2>
  ${table(['Outcome', 'Questions', 'Share'], a.outcomes.map(o => [o.label, formatNumber(o.value), pct(o.value, questions)]))}

  <h2>Knowledge sources by type</h2>
  ${table(['Type', 'Sources'], a.sourceDistribution.map(s => [s.label, formatNumber(s.value)]))}

  <h2>Source processing status</h2>
  ${table(['Status', 'Sources'], a.processing.map(p => [p.label, formatNumber(p.value)]))}

  <h2>Most active users</h2>
  ${a.topUsers.length ? table(['User', 'Questions', 'Conversations'], a.topUsers.map(u => [u.name, formatNumber(u.questions), formatNumber(u.conversations)])) : '<p class="meta">No user activity.</p>'}

  <h2>Most referenced sources</h2>
  ${a.topSources.length ? table(['Source', 'Citations'], a.topSources.map(s => [s.title, formatNumber(s.citations)])) : '<p class="meta">No citations recorded.</p>'}

  <footer>Generated by the DTS AI admin console from the analytics API.</footer>
</main></body></html>`;
}

/** Build and download the HTML report. Returns the filename. */
export function downloadAnalyticsReport(analytics, range) {
  const name = `dts-ai-admin-analytics-report-${rangeSlug(range, analytics)}-${formatInputDate(new Date())}.html`;
  downloadFile(name, buildAnalyticsReport(analytics, range), 'text/html;charset=utf-8');
  return name;
}
