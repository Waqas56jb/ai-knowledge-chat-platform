/**
 * Analytics — GET /admin/analytics/overview, computed server-side from real usage.
 * range: 'today' | '7d' | '30d' | '90d' | { from: 'YYYY-MM-DD', to: 'YYYY-MM-DD' }
 */
import { apiGet, downloadCsv } from './api';

const rangeQuery = range => (typeof range === 'object' && range
  ? { range: 'custom', from: range.from, to: range.to }
  : { range: range || '30d' });

/** Server totals are snake_case; the charts read camelCase. */
const mapTotals = (t = {}) => ({
  newUsers: t.new_users ?? 0,
  activeUsers: t.active_users ?? 0,
  conversations: t.conversations ?? 0,
  questions: t.questions ?? 0,
  answered: t.answered ?? 0,
  insufficient: t.insufficient ?? 0,
  outOfScope: t.out_of_scope ?? 0,
  errors: t.errors ?? 0,
  jobsCompleted: t.jobs_completed ?? 0,
  jobsFailed: t.jobs_failed ?? 0,
  sourcesAdded: t.sources_added ?? 0,
  unsupported: t.unsupported ?? 0
});

/**
 * { range (as requested), days, from, to, hourly, series, totals, previous, kpis, sourceDistribution,
 *   outcomes, processing, topUsers, topSources }
 */
export async function getAnalytics(range = '30d') {
  const a = await apiGet('/admin/analytics/overview', rangeQuery(range));
  return {
    ...a,
    range,
    series: a.series || [],
    totals: mapTotals(a.totals),
    previous: mapTotals(a.previous),
    sourceDistribution: a.sourceDistribution || [],
    outcomes: a.outcomes || [],
    processing: a.processing || [],
    topUsers: a.topUsers || [],
    topSources: a.topSources || []
  };
}

/** CSV of the same range, generated by the server. */
export const exportAnalytics = range => downloadCsv('/admin/analytics/overview', rangeQuery(range), `analytics-${typeof range === 'object' ? `${range.from}-to-${range.to}` : range}`);
